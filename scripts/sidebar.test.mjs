// Run: node --test scripts/sidebar.test.mjs
// API → Getting Started is a reading path: its pages are real items there (so Previous / Next walk it in
// order), and their old sections (TurboSign, TurboDocx Templating) list them as shortcuts, so each page
// sits in the Previous / Next order exactly once.
import test from 'node:test';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';

const require = createRequire(import.meta.url);
const apiSidebar = require('../docs/API/sidebar.js');
const {GETTING_STARTED_GUIDES, guidesAsShortcuts} = require('../sidebar-guides.js');

test('API Getting Started lists every item as a real page, in reading order', () => {
  const gettingStarted = apiSidebar.find((item) => item.label === 'Getting Started');
  assert.deepEqual(
    gettingStarted.items.map((item) => [item.type, item.id]),
    [
      ['doc', 'API/turbodocx-api-documentation'],
      ['doc', 'API/Deliverable-API'],
      ...GETTING_STARTED_GUIDES.map(({id}) => ['doc', id]),
    ],
  );
});

test('autogenerated sections list the Getting Started guides as shortcuts, and nothing else changes', () => {
  const generated = [
    {type: 'doc', id: 'TurboSign/Setting-up-TurboSign'},
    {type: 'doc', id: 'TurboSign/API-Signatures', className: 'x'},
    {
      type: 'category',
      label: 'Nested',
      items: [
        {type: 'doc', id: 'TurboSign/Webhooks', label: 'Webhooks'},
        {type: 'doc', id: 'TurboSign/Other'},
      ],
    },
    {type: 'link', href: 'https://example.com', label: 'Out'},
  ];
  assert.deepEqual(guidesAsShortcuts(generated), [
    {type: 'doc', id: 'TurboSign/Setting-up-TurboSign'},
    {type: 'ref', id: 'TurboSign/API-Signatures', className: 'x'},
    {
      type: 'category',
      label: 'Nested',
      items: [
        {type: 'ref', id: 'TurboSign/Webhooks', label: 'Webhooks'},
        {type: 'doc', id: 'TurboSign/Other'},
      ],
    },
    {type: 'link', href: 'https://example.com', label: 'Out'},
  ]);
});
